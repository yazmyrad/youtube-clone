#!/usr/bin/env bash
# Creates the development env files. Safe to run again: existing secrets are kept.
#   .env.dev      settings for the dev compose stack
#   backend/.env  connection settings for tools run on the host (alembic, pytest, uvicorn)
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")/.."

MARKER="# Generated by scripts/dev-env.sh from .env.dev. Edit .env.dev, then run: make env"

random_hex() { head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# The database port isn't 5432, so it can't clash with, or be confused with, a Postgres
# already running on this machine.
if [ ! -f .env.dev ]; then
    (
        umask 077
        cat > .env.dev <<EOF
HTTP_PORT=8080
DEV_DB_PORT=55432
POSTGRES_USER=app
POSTGRES_DB=app
POSTGRES_PASSWORD=$(random_hex)
EOF
    )
    echo "Created .env.dev"
fi
# Secrets added by later versions are appended, so existing ones are kept.
grep -q '^DEV_MINIO_PORT=' .env.dev || echo "DEV_MINIO_PORT=59000" >> .env.dev
grep -q '^JWT_SECRET=' .env.dev || echo "JWT_SECRET=$(random_hex)" >> .env.dev
grep -q '^PLAYBACK_SECRET=' .env.dev || echo "PLAYBACK_SECRET=$(random_hex)" >> .env.dev
grep -q '^MINIO_ROOT_USER=' .env.dev || echo "MINIO_ROOT_USER=minio-root" >> .env.dev
grep -q '^MINIO_ROOT_PASSWORD=' .env.dev || echo "MINIO_ROOT_PASSWORD=$(random_hex)" >> .env.dev
grep -q '^MINIO_APP_ACCESS_KEY=' .env.dev || echo "MINIO_APP_ACCESS_KEY=app" >> .env.dev
grep -q '^MINIO_APP_SECRET_KEY=' .env.dev || echo "MINIO_APP_SECRET_KEY=$(random_hex)" >> .env.dev

set -a
# shellcheck disable=SC1091
. ./.env.dev
set +a

if [ -f backend/.env ] && ! grep -qxF "$MARKER" backend/.env; then
    echo "Leaving backend/.env alone: it wasn't generated by this script." >&2
    echo "Delete it and run 'make env' to use the dev database." >&2
    exit 0
fi

db="postgresql+asyncpg://${POSTGRES_USER}:${POSTGRES_PASSWORD}@127.0.0.1:${DEV_DB_PORT}"
minio="http://127.0.0.1:${DEV_MINIO_PORT}"
(
    umask 077
    cat > backend/.env <<EOF
$MARKER
DATABASE_URL=${db}/${POSTGRES_DB}
TEST_DATABASE_URL=${db}/${POSTGRES_DB}_test
JWT_SECRET=${JWT_SECRET}
PLAYBACK_SECRET=${PLAYBACK_SECRET}
MINIO_ENDPOINT=${minio}
MINIO_APP_ACCESS_KEY=${MINIO_APP_ACCESS_KEY}
MINIO_APP_SECRET_KEY=${MINIO_APP_SECRET_KEY}
TEST_MINIO_ENDPOINT=${minio}
TEST_MINIO_ACCESS_KEY=${MINIO_ROOT_USER}
TEST_MINIO_SECRET_KEY=${MINIO_ROOT_PASSWORD}
EOF
)
